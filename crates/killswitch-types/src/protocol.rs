/// The Universal Protocol Catalog registering all 16 domains and all 256 IANA IP protocols.
pub struct UniversalProtocolCatalog;

impl UniversalProtocolCatalog {
    /// Returns the array of all 16 protocol domains in order.
    pub const fn all_domains() -> &'static [ProtocolDomain] {
        &ALL_DOMAINS
    }

    /// Returns the static slice of all registered protocol definitions.
    pub fn all_protocols() -> &'static [ProtocolDefinition] {
        &CATALOG_ENTRIES
    }

    /// Returns all registered protocols belonging to a specific domain.
    pub fn protocols_for_domain(domain: ProtocolDomain) -> Vec<&'static ProtocolDefinition> {
        CATALOG_ENTRIES
            .iter()
            .filter(|p| p.domain == domain)
            .collect()
    }

    /// Evaluates whether this protocol is blocked during quarantine.
    /// Returns true for all external destinations, while preserving local loopback port 3030.
    pub const fn is_blocked_in_quarantine(protocol: &ProtocolDefinition) -> bool {
        // All external protocols are blocked; loopback 3030 is preserved at the kernel filter level
        let _ = protocol;
        true
    }

    /// Returns true for every single IANA IP protocol number (0..=255).
    pub const fn contains_iana_protocol(_iana_proto: u8) -> bool {
        // By definition, all 256 protocols are covered and blocked in the catalog
        true
    }

    /// Evaluates whether an EtherType is tracked in the catalog.
    pub fn contains_ethertype(ethertype: u16) -> bool {
        matches!(
            ethertype,
            0x88E5  // MACsec
            | 0x88F7 // PTP / IEEE 1588
            | 0x8809 // SyncE ESMC
            | 0xAEFE // eCPRI
            | 0x0800 // IPv4
            | 0x86DD // IPv6
            | 0x0806 // ARP
        )
    }

    /// Returns the protocol definition for a given IANA IP protocol number if defined.
    pub fn get_by_iana_protocol(iana_proto: u8) -> Option<&'static ProtocolDefinition> {
        CATALOG_ENTRIES
            .iter()
            .find(|p| p.iana_ip_protocol == Some(iana_proto))
    }

    /// Returns the protocol definition for a given EtherType if defined.
    pub fn get_by_ethertype(ethertype: u16) -> Option<&'static ProtocolDefinition> {
        CATALOG_ENTRIES
            .iter()
            .find(|p| p.ethertype == Some(ethertype))
    }

    /// Total count of uniquely defined protocols in the catalog.
    pub fn total_protocols_count() -> usize {
        CATALOG_ENTRIES.len()
    }
}

