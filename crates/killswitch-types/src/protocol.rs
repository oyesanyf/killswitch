#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_all_16_domains_present() {
        let domains = UniversalProtocolCatalog::all_domains();
        assert_eq!(domains.len(), 16);
        for (i, d) in domains.iter().enumerate() {
            assert_eq!(d.domain_number(), (i + 1) as u8);
            assert!(!d.name().is_empty());
        }
    }

    #[test]
    fn test_catalog_integrity() {
        let all = UniversalProtocolCatalog::all_protocols();
        assert!(all.len() >= 100);

        // Verify each domain has at least one protocol
        for d in UniversalProtocolCatalog::all_domains() {
            let in_domain = UniversalProtocolCatalog::protocols_for_domain(*d);
            assert!(
                !in_domain.is_empty(),
                "Domain {:?} has no registered protocols",
                d
            );
        }
    }

    #[test]
    fn test_ethertype_and_iana_coverage() {
        assert!(UniversalProtocolCatalog::contains_ethertype(0x88E5));
        assert!(UniversalProtocolCatalog::contains_ethertype(0x88F7));
        assert!(UniversalProtocolCatalog::contains_ethertype(0x8809));
        assert!(UniversalProtocolCatalog::contains_ethertype(0xAEFE));

        // Test all 256 IANA IP protocols evaluate to true
        for proto in 0..=255u8 {
            assert!(UniversalProtocolCatalog::contains_iana_protocol(proto));
        }

        // Test lookup by IANA protocol
        let tcp = UniversalProtocolCatalog::get_by_iana_protocol(6).expect("TCP found");
        assert_eq!(tcp.id, "TCP");

        let udp = UniversalProtocolCatalog::get_by_iana_protocol(17).expect("UDP found");
        assert_eq!(udp.id, "UDP");

        // Test lookup by EtherType
        let macsec = UniversalProtocolCatalog::get_by_ethertype(0x88E5).expect("MACsec found");
        assert_eq!(macsec.id, "MACsec");

        let ptp = UniversalProtocolCatalog::get_by_ethertype(0x88F7).expect("PTP found");
        assert!(ptp.id == "PTP" || ptp.id == "WhiteRabbit");
    }
}
